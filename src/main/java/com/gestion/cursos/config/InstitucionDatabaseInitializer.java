package com.gestion.cursos.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Inicializador automático del esquema y datos base de la Institución
 * (PostgreSQL / Supabase / H2).
 * Requisitos: Sección 3.2, 4.1.1, 4.1.2.
 */
@Component
@Order(1)
public class InstitucionDatabaseInitializer implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(InstitucionDatabaseInitializer.class);

    private final JdbcTemplate jdbcTemplate;

    public InstitucionDatabaseInitializer(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(String... args) {
        log.info("Inicializando esquema de base de datos propia de la institución...");

        try {
            // 1. Tabla empresas
            jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS empresas (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre VARCHAR(150) NOT NULL,
                    contacto VARCHAR(100),
                    email VARCHAR(120) NOT NULL UNIQUE,
                    password VARCHAR(100) DEFAULT 'empresa123',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """);

            // 2. Tabla cursos (incluye: nombre, descripción, programa, presupuesto, fechas e informe de resultados)
            jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS cursos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    curso_id VARCHAR(64) NOT NULL UNIQUE,
                    empresa_id BIGINT NOT NULL,
                    process_instance_id VARCHAR(64),
                    nombre VARCHAR(180) NOT NULL,
                    descripcion TEXT,
                    categoria VARCHAR(100),
                    cupo_estimado INT DEFAULT 20,
                    fechas_preferidas VARCHAR(255),
                    programa TEXT,
                    presupuesto VARCHAR(100),
                    fechas_posibles VARCHAR(255),
                    fecha_inicio VARCHAR(100),
                    estado VARCHAR(60) NOT NULL DEFAULT 'pendiente',
                    informe_resultados TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT fk_cursos_empresa FOREIGN KEY (empresa_id) REFERENCES empresas(id)
                )
            """);

            // Índices recomendados
            try {
                jdbcTemplate.execute("CREATE INDEX IF NOT EXISTS idx_cursos_process_instance_id ON cursos(process_instance_id)");
                jdbcTemplate.execute("CREATE INDEX IF NOT EXISTS idx_cursos_empresa_id ON cursos(empresa_id)");
            } catch (Exception ex) {
                // Algunos motores manejan IF NOT EXISTS en índices de manera distinta
                log.debug("Nota sobre índices: {}", ex.getMessage());
            }

            // 3. Cargar datos de prueba si la tabla empresas está vacía
            Integer countEmpresas = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM empresas", Integer.class);
            if (countEmpresas != null && countEmpresas == 0) {
                log.info("Cargando datos iniciales de prueba en la base de datos de la institución...");
                jdbcTemplate.execute("""
                    INSERT INTO empresas (nombre, contacto, email, password) VALUES
                    ('Tech Solutions S.A.', 'Carlos Gómez', 'contacto@techsolutions.com', 'empresa123'),
                    ('Innovación & Logística Global SRL', 'Mariana López', 'mlopez@innovalog.com', 'empresa123')
                """);

                jdbcTemplate.execute("""
                    INSERT INTO cursos (
                        curso_id, empresa_id, process_instance_id, nombre, descripcion, categoria,
                        cupo_estimado, fechas_preferidas, programa, presupuesto, fechas_posibles,
                        fecha_inicio, estado, informe_resultados
                    ) VALUES (
                        'CURSO-BPM-101', 1, 'inst-demo-101', 'Capacitación en Optimización de Procesos con Flowable BPM',
                        'Taller sobre orquestación de procesos de negocio, BPMN 2.0 y balanceo de carga.',
                        'Ingeniería y Procesos', 25, 'Diciembre 2026',
                        'Módulo 1: Fundamentos. Módulo 2: DMN. Módulo 3: Listeners.', '$ 1.250.000',
                        '2026-12-01 al 2026-12-15', '2026-12-05', 'en_preparacion', NULL
                    )
                """);
                log.info("Datos de prueba iniciales cargados con éxito.");
            }

            log.info("Base de datos de la institución inicializada correctamente.");
        } catch (Exception e) {
            log.error("Error al inicializar la base de datos institucional: {}", e.getMessage(), e);
        }
    }
}
