-- ============================================================================
-- CONSULTA DE VERIFICACIÓN
-- ============================================================================
SELECT 
    c.id AS curso_id,
    c.nombre AS curso_nombre,
    c.estado AS curso_estado,
    c.process_instance_id,
    c.fecha_inicio,
    e.nombre AS empresa_cliente,
    e.contacto AS referente_empresa
FROM cursos c
INNER JOIN empresas e ON c.empresa_id = e.id;
