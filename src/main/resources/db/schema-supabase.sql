DROP TABLE IF EXISTS cursos CASCADE;
DROP TABLE IF EXISTS empresas CASCADE;

-- ============================================================================
-- 1. TABLA: empresas (Sección 3.2 y 4.1.2)
-- Almacena las empresas solicitantes y sus credenciales de acceso para seguimiento.
-- ============================================================================
CREATE TABLE empresas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    contacto VARCHAR(100),
    email VARCHAR(120) NOT NULL,
    password VARCHAR(100) DEFAULT 'empresa123',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT uq_empresas_email UNIQUE (email)
);

-- ============================================================================
-- 2. TABLA: cursos (Sección 3.2, 3.4 y 4.1)
-- Almacena la información de los cursos solicitados:
-- nombre, descripción, programa, presupuesto, fechas e informe de resultados.
-- Cada curso queda vinculado con su correspondiente instancia en Flowable.
-- ============================================================================
CREATE TABLE cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id VARCHAR(64) NOT NULL UNIQUE,
    empresa_id BIGINT NOT NULL,
    process_instance_id VARCHAR(64),
    nombre VARCHAR(180) NOT NULL,
    descripcion TEXT,
    categoria VARCHAR(100),
    cupo_estimado INT DEFAULT 20,
    fechas_preferidas VARCHAR(255),
    programa TEXT,
    presupuesto VARCHAR(100),
    fechas_posibles VARCHAR(255),
    fecha_inicio VARCHAR(100),
    estado VARCHAR(60) NOT NULL DEFAULT 'pendiente',
    informe_resultados TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_cursos_empresa 
        FOREIGN KEY (empresa_id) 
        REFERENCES empresas(id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE
);

-- Índices para optimización de consultas
CREATE INDEX idx_cursos_empresa_id ON cursos(empresa_id);
CREATE INDEX idx_cursos_process_instance_id ON cursos(process_instance_id);
CREATE INDEX idx_cursos_estado ON cursos(estado);

