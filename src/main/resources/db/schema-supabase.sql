-- ============================================================================

-- Habilitar extensión para funciones criptográficas y UUID si se requiere en Supabase
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Limpieza preventiva de tablas (en orden de dependencias)
DROP TABLE IF EXISTS cursos CASCADE;
DROP TABLE IF EXISTS empresas CASCADE;

-- ============================================================================
-- 1. TABLA: empresas
-- ============================================================================
CREATE TABLE empresas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    contacto VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT uq_empresas_email UNIQUE (email)
);

COMMENT ON TABLE empresas IS 'Entidades o clientes corporativos que solicitan cursos de capacitación';
COMMENT ON COLUMN empresas.id IS 'Identificador único de la empresa';
COMMENT ON COLUMN empresas.nombre IS 'Razón social o nombre comercial de la empresa';
COMMENT ON COLUMN empresas.contacto IS 'Persona o referente de contacto principal';
COMMENT ON COLUMN empresas.email IS 'Correo electrónico corporativo de contacto';

-- ============================================================================
-- 2. TABLA: cursos
-- ============================================================================
CREATE TABLE cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    process_instance_id VARCHAR(64), -- Clave de vinculación con la instancia de Flowable (ACT_RU_EXECUTION)
    nombre VARCHAR(180) NOT NULL,
    descripcion TEXT,
    estado VARCHAR(50) NOT NULL DEFAULT 'pendiente',
    fecha_inicio DATE,
    informe_resultados TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    -- Clave foránea referenciando a empresas
    CONSTRAINT fk_cursos_empresa 
        FOREIGN KEY (empresa_id) 
        REFERENCES empresas(id) 
        ON DELETE RESTRICT 
        ON UPDATE CASCADE,

    -- Restricción de dominio para estados válidos (Sección 3.4)
    CONSTRAINT chk_cursos_estado 
        CHECK (estado IN ('pendiente', 'en_preparacion', 'finalizado', 'cancelado', 'rechazado', 'no viable', 'cerrado por falta de respuesta'))
);

COMMENT ON TABLE cursos IS 'Cursos solicitados y gestionados mediante el workflow BPMN de Flowable';
COMMENT ON COLUMN cursos.empresa_id IS 'Empresa asociada a la solicitud del curso';
COMMENT ON COLUMN cursos.process_instance_id IS 'ID de la instancia de proceso en Flowable para trazabilidad';
COMMENT ON COLUMN cursos.estado IS 'Estado actual del ciclo de vida del curso';
COMMENT ON COLUMN cursos.informe_resultados IS 'Observaciones, calificaciones o informe generado al concluir el curso';

-- Índices recomendados para optimización de consultas y joins
CREATE INDEX idx_cursos_empresa_id ON cursos(empresa_id);
CREATE INDEX idx_cursos_process_instance_id ON cursos(process_instance_id);
CREATE INDEX idx_cursos_estado ON cursos(estado);

-- Trigger para mantener actualizado el campo updated_at automáticamente
CREATE OR REPLACE FUNCTION actualizar_timestamp_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_actualizar_cursos_updated_at
BEFORE UPDATE ON cursos
FOR EACH ROW
EXECUTE FUNCTION actualizar_timestamp_updated_at();

